# The class remains similar but we optimize contrast
class Canvas:
    def __init__(self, width=1024, height=1024):
        self.width, self.height = width, height
        self.data = bytearray([255] * (width * height * 3)) # White background

    def fill_rect(self, x, y, w, h, color):
        x0, y0 = max(0, int(x)), max(0, int(y))
        x1, y1 = min(self.width, int(x + w)), min(self.height, int(y + h))
        for cy in range(y0, y1):
            for cx in range(x0, x1):
                idx = (cy * self.width + cx) * 3
                self.data[idx] = color[0]
                self.data[idx+1] = color[1]
                self.data[idx+2] = color[2]

    def draw_char(self, char, x, y, scale, color):
        glyph = FONT_8X8.get(char.upper(), FONT_8X8.get('?', [0]*8))
        for r, row in enumerate(glyph):
            for c in range(8):
                if row & (1 << (7 - c)):
                    if scale == 1:
                        if 0 <= x+c < self.width and 0 <= y+r < self.height:
                            idx = ((y+r)*self.width + (x+c))*3
                            self.data[idx:idx+3] = color
                    else:
                        self.fill_rect(x+c*scale, y+r*scale, scale, scale, color)

    def draw_text(self, text, x, y, scale=1, color=(0, 0, 0), spacing=1):
        for ch in text:
            self.draw_char(ch, x, y, scale, color)
            x += (8 * scale + spacing)

    def to_png(self):
        raw = bytearray()
        for y in range(self.height):
            raw.append(0)
            raw.extend(self.data[y*self.width*3:(y+1)*self.width*3])
        compressed = zlib.compress(bytes(raw), level=9)
        def chunk(tag, data):
            return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 1024, 1024, 8, 2, 0, 0, 0)) + chunk(b"IDAT", compressed) + chunk(b"IEND", b"")

